"""Portable full-backup container helper. Standard library only; never executes SQL."""
import argparse
from datetime import datetime, timezone
import hashlib
import json
import os
from pathlib import Path, PurePosixPath
import re
import shutil
import tarfile
import tempfile


FORMAT = "hardware-history-explorer/full-backup"
CHUNK = 1024 * 1024


def digest(path):
    value = hashlib.sha256()
    with path.open("rb") as stream:
        for chunk in iter(lambda: stream.read(CHUNK), b""):
            value.update(chunk)
    return value.hexdigest()


def portable_name(name):
    # Uploads generated by HHE are flat UUID WebP files. Do not allow an archive
    # to create paths, links, device files or Windows alternate data streams.
    return (bool(name) and name not in {".", ".."} and
            not any(char in name for char in '/\\:<>"|?*') and
            not any(ord(char) < 32 for char in name) and
            not name.endswith((".", " ")) and
            not re.match(r"^(CON|PRN|AUX|NUL|COM[1-9]|LPT[1-9])(?:\.|$)", name, re.I))


def upload_files(uploads):
    files = sorted(uploads.iterdir())
    if any(not file.is_file() or file.is_symlink() or not portable_name(file.name) for file in files):
        raise ValueError("La cartella fotografie contiene directory, link o nomi non portabili: backup interrotto.")
    return files


def pack(work, uploads):
    database = work / "database.dump"
    with database.open("rb") as stream:
        if stream.read(5) != b"PGDMP":
            raise ValueError("Dump PostgreSQL non valido.")
    metadata = json.loads((work / "metadata.json").read_text(encoding="utf-8-sig"))
    files = {"database.dump": database}
    files.update({f"uploads/{file.name}": file for file in upload_files(uploads)})
    manifest = {
        "format": FORMAT, "version": 1,
        "created_at": datetime.now(timezone.utc).isoformat(),
        "source_project": metadata["project"], "git_commit": metadata.get("git_commit"),
        "git_dirty": metadata.get("git_dirty", False),
        "postgres_major": int(metadata["postgres_major"]),
        "files": {name: {"size": path.stat().st_size, "sha256": digest(path)}
                  for name, path in files.items()},
    }
    manifest_path = work / "manifest.json"
    manifest_path.write_text(json.dumps(manifest, ensure_ascii=False, indent=2), encoding="utf-8")
    output = work / "archive.hhe-backup.tar.gz"
    try:
        with tarfile.open(output, "w:gz", compresslevel=6) as archive:
            archive.add(manifest_path, arcname="manifest.json", recursive=False)
            for name, path in files.items():
                archive.add(path, arcname=name, recursive=False)
    except BaseException:
        output.unlink(missing_ok=True)
        raise
    print(f"Backup completo: database e {len(files) - 1} file fotografici.")


def validate_manifest(manifest):
    if manifest.get("format") != FORMAT or manifest.get("version") != 1:
        raise ValueError("Formato/versione del backup non supportato.")
    files = manifest.get("files")
    if not isinstance(files, dict) or "database.dump" not in files or len(files) > 100001:
        raise ValueError("Elenco file del backup non valido.")
    if type(manifest.get("postgres_major")) is not int or manifest["postgres_major"] < 12:
        raise ValueError("Versione PostgreSQL mancante/non valida.")
    seen = set()
    for name, entry in files.items():
        if name != "database.dump":
            path = PurePosixPath(name)
            if len(path.parts) != 2 or path.parts[0] != "uploads" or not portable_name(path.parts[1]) or str(path) != name:
                raise ValueError("Percorso non consentito nel backup.")
        if name.casefold() in seen:
            raise ValueError("Nomi file duplicati su Windows.")
        seen.add(name.casefold())
        if (not isinstance(entry, dict) or type(entry.get("size")) is not int or entry["size"] < 0 or
                not re.fullmatch(r"[a-f0-9]{64}", str(entry.get("sha256", "")))):
            raise ValueError("Dimensione/hash del file non valido.")
    return files


def unpack(work):
    destination = work / "validated"
    if destination.exists():
        raise ValueError("La cartella di verifica deve essere nuova.")
    destination.mkdir()
    try:
        with tarfile.open(work / "input.hhe-backup.tar.gz", "r:gz") as archive:
            first = archive.next()
            if first is None or first.name != "manifest.json" or not first.isfile() or first.size > 32 * CHUNK:
                raise ValueError("Manifest iniziale assente o non valido.")
            manifest = json.load(archive.extractfile(first))
            files = validate_manifest(manifest)
            if sum(entry["size"] for entry in files.values()) + 64 * CHUNK > shutil.disk_usage(work).free:
                raise ValueError("Spazio disco insufficiente per estrarre il backup.")
            seen = set()
            while (member := archive.next()) is not None:
                if (member.name in seen or member.name not in files or not member.isfile() or
                        member.size != files[member.name]["size"] or member.sparse is not None):
                    raise ValueError("File duplicato, inatteso o non sicuro nel backup.")
                seen.add(member.name)
                output = destination / member.name
                output.parent.mkdir(exist_ok=True)
                with archive.extractfile(member) as source, output.open("xb") as target:
                    shutil.copyfileobj(source, target, CHUNK)
                if digest(output) != files[member.name]["sha256"]:
                    raise ValueError(f"Hash non valido: {member.name}")
            if seen != set(files):
                raise ValueError("Il backup e incompleto.")
        with (destination / "database.dump").open("rb") as stream:
            if stream.read(5) != b"PGDMP":
                raise ValueError("Dump PostgreSQL non valido.")
        (destination / "uploads").mkdir(exist_ok=True)
        (work / "verified-manifest.json").write_text(json.dumps(manifest), encoding="utf-8")
        print(f"Backup verificato: {len(files) - 1} fotografie, tutti gli hash SHA-256 corretti.")
    except BaseException:
        shutil.rmtree(destination)
        raise


def install(work, uploads):
    """Replace flat uploaded files; roll back ordinary filesystem errors."""
    incoming = work / "validated" / "uploads"
    new_files = upload_files(incoming)
    old_files = upload_files(uploads)
    if sum(file.stat().st_size for file in new_files) + 64 * CHUNK > shutil.disk_usage(uploads).free:
        raise ValueError("Spazio insufficiente nel volume fotografie.")
    staging = Path(tempfile.mkdtemp(prefix=".hhe-restore-", dir=uploads))
    old, new = staging / "old", staging / "new"
    old.mkdir()
    new.mkdir()
    moved_old, moved_new = [], []
    cleanup = True
    try:
        for file in new_files:
            shutil.copy2(file, new / file.name)
        for file in old_files:
            file.rename(old / file.name)
            moved_old.append(file.name)
        for file in new_files:
            (new / file.name).rename(uploads / file.name)
            moved_new.append(file.name)
    except BaseException:
        cleanup = False
        for name in moved_new:
            (uploads / name).unlink()
        for name in moved_old:
            (old / name).rename(uploads / name)
        cleanup = True
        raise
    finally:
        # On a rollback error leave recovery files for manual recovery.
        if cleanup:
            shutil.rmtree(staging)
    print(f"Ripristinati {len(new_files)} file fotografici.")


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("operation", choices=("pack", "unpack", "install"))
    parser.add_argument("--work", type=Path, default=Path("/transfer"))
    parser.add_argument("--uploads", type=Path, default=Path(os.getenv("UPLOAD_DIR", "/code/uploads")))
    args = parser.parse_args()
    os.umask(0o077)
    try:
        if args.operation == "pack":
            pack(args.work, args.uploads)
        elif args.operation == "unpack":
            unpack(args.work)
        else:
            install(args.work, args.uploads)
    finally:
        # A Linux Docker process may run as root. Its host-side working files
        # must remain readable/removable by the user who launched PowerShell.
        if os.geteuid() == 0:
            owner = args.work.stat()
            for path in args.work.rglob("*"):
                current = path.lstat()
                if (current.st_uid, current.st_gid) != (owner.st_uid, owner.st_gid):
                    os.chown(path, owner.st_uid, owner.st_gid, follow_symlinks=False)
